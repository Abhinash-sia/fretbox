'use client';

import * as React from 'react';
import {
  ResponsiveContainer,
  AreaChart,
  Area,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
} from 'recharts';
import { Card, CardHeader, CardTitle, CardDescription, CardContent } from '@/components/ui/card';
import { ForecastItem } from '../types/prediction';

interface PredictionChartProps {
  forecast: ForecastItem[];
}

export function PredictionChart({ forecast }: PredictionChartProps) {
  if (!forecast || forecast.length === 0) return null;

  return (
    <Card className="border-border bg-card">
      <CardHeader className="pb-2">
        <CardTitle className="text-sm font-bold flex items-center justify-between">
          <span>Complaint Demand Forecast Curve</span>
          <span className="text-xs font-mono text-muted-foreground font-normal">
            {forecast.length}-Day Iterative Horizon
          </span>
        </CardTitle>
        <CardDescription className="text-xs text-muted-foreground">
          Predicted daily operational complaint volume generated by scikit-learn time-series model.
        </CardDescription>
      </CardHeader>
      <CardContent className="pt-2">
        <div className="h-64 w-full">
          <ResponsiveContainer width="100%" height="100%">
            <AreaChart
              data={forecast}
              margin={{ top: 10, right: 10, left: -20, bottom: 0 }}
            >
              <defs>
                <linearGradient id="forecastGradient" x1="0" y1="0" x2="0" y2="1">
                  <stop offset="5%" stopColor="hsl(var(--primary))" stopOpacity={0.3} />
                  <stop offset="95%" stopColor="hsl(var(--primary))" stopOpacity={0.0} />
                </linearGradient>
              </defs>
              <CartesianGrid strokeDasharray="3 3" vertical={false} stroke="hsl(var(--border))" />
              <XAxis
                dataKey="date"
                tickLine={false}
                axisLine={false}
                tickMargin={8}
                className="text-[10px] font-mono fill-muted-foreground"
                tickFormatter={(value) => {
                  const parts = value.split('-');
                  return parts.length === 3 ? `${parts[1]}/${parts[2]}` : value;
                }}
              />
              <YAxis
                tickLine={false}
                axisLine={false}
                tickMargin={8}
                className="text-[10px] font-mono fill-muted-foreground"
                allowDecimals={false}
              />
              <Tooltip
                content={({ active, payload, label }) => {
                  if (active && payload && payload.length) {
                    const val = payload[0].value;
                    return (
                      <div className="rounded-md border border-border bg-popover p-2 shadow-md text-xs">
                        <div className="font-semibold text-popover-foreground">{label}</div>
                        <div className="text-primary font-medium mt-0.5">
                          Predicted Complaints: <span className="font-mono font-bold">{val}</span>
                        </div>
                      </div>
                    );
                  }
                  return null;
                }}
              />
              <Area
                type="monotone"
                dataKey="predictedComplaints"
                stroke="hsl(var(--primary))"
                strokeWidth={2}
                fillOpacity={1}
                fill="url(#forecastGradient)"
                activeDot={{ r: 5, strokeWidth: 0 }}
              />
            </AreaChart>
          </ResponsiveContainer>
        </div>
      </CardContent>
    </Card>
  );
}
